-- AP CP2: College Lost & Found database (PostgreSQL 15+)
-- Aligned with dbms/01_normalization.md (CP1): 7 final 3NF relations.
-- Run once in a fresh test database with: psql -v ON_ERROR_STOP=1 -d college_lost_found_cp2 -f dbms/03_schema.sql
-- Distinctive details and claim proof are PRIVATE: enforce access rules in the application.

BEGIN;

-- One student has one registered college email address.
CREATE TABLE students (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_email VARCHAR(255) NOT NULL UNIQUE,
    full_name VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT students_email_not_blank CHECK (btrim(college_email) <> ''),
    CONSTRAINT students_name_not_blank CHECK (btrim(full_name) <> '')
);

-- Centralized classification of lost/found items.
CREATE TABLE categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL UNIQUE,
    CONSTRAINT categories_name_not_blank CHECK (btrim(category_name) <> '')
);

-- Exactly one student and one category own each LOST or FOUND report.
CREATE TABLE item_reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
    category_id BIGINT NOT NULL REFERENCES categories(category_id) ON DELETE RESTRICT,
    report_type VARCHAR(5) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    distinctive_details_private TEXT,
    event_date DATE NOT NULL,
    event_location VARCHAR(255) NOT NULL,
    reported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    CONSTRAINT item_reports_type_valid CHECK (report_type IN ('LOST', 'FOUND')),
    CONSTRAINT item_reports_status_valid CHECK (status IN ('OPEN', 'MATCHED', 'RESOLVED', 'CLOSED')),
    CONSTRAINT item_reports_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT item_reports_location_not_blank CHECK (btrim(event_location) <> '')
);

-- One report can contain several photos. Store URLs, not binary images.
CREATE TABLE report_images (
    image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES item_reports(report_id) ON DELETE CASCADE,
    image_url TEXT NOT NULL,
    CONSTRAINT report_images_url_not_blank CHECK (btrim(image_url) <> '')
);

-- Candidate pairs are NOT proof of ownership. The pair is the composite PK.
CREATE TABLE possible_matches (
    lost_report_id BIGINT NOT NULL REFERENCES item_reports(report_id) ON DELETE CASCADE,
    found_report_id BIGINT NOT NULL REFERENCES item_reports(report_id) ON DELETE CASCADE,
    match_score NUMERIC(5,4) NOT NULL,
    matched_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    match_status VARCHAR(20) NOT NULL DEFAULT 'SUGGESTED',
    CONSTRAINT possible_matches_pk PRIMARY KEY (lost_report_id, found_report_id),
    CONSTRAINT possible_matches_not_same_report CHECK (lost_report_id <> found_report_id),
    CONSTRAINT possible_matches_score_range CHECK (match_score BETWEEN 0 AND 1),
    CONSTRAINT possible_matches_status_valid CHECK (match_status IN ('SUGGESTED', 'UNDER_REVIEW', 'DISMISSED'))
);

-- Ownership evidence belongs to an actual candidate pair.
-- A final decision must include a different verifier and a verification time.
CREATE TABLE ownership_claims (
    claim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lost_report_id BIGINT NOT NULL,
    found_report_id BIGINT NOT NULL,
    claimant_student_id BIGINT NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
    proof_description_private TEXT NOT NULL,
    verification_status VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    verified_by_student_id BIGINT REFERENCES students(student_id) ON DELETE RESTRICT,
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ownership_claims_match_fk
        FOREIGN KEY (lost_report_id, found_report_id)
        REFERENCES possible_matches(lost_report_id, found_report_id)
        ON DELETE RESTRICT,
    CONSTRAINT ownership_claims_proof_not_blank CHECK (btrim(proof_description_private) <> ''),
    CONSTRAINT ownership_claims_status_valid CHECK (verification_status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ownership_claims_verification_consistent CHECK (
        (verification_status = 'PENDING' AND verified_by_student_id IS NULL AND verified_at IS NULL)
        OR
        (verification_status IN ('APPROVED', 'REJECTED') AND verified_by_student_id IS NOT NULL AND verified_at IS NOT NULL)
    ),
    CONSTRAINT ownership_claims_no_self_verification CHECK (
        verified_by_student_id IS NULL OR verified_by_student_id <> claimant_student_id
    )
);

-- One approved claim can result in at most one recorded physical handover.
CREATE TABLE handovers (
    handover_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL UNIQUE REFERENCES ownership_claims(claim_id) ON DELETE RESTRICT,
    handed_over_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    handed_over_by_student_id BIGINT NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
    received_by_student_id BIGINT NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
    notes TEXT,
    CONSTRAINT handovers_different_participants CHECK (
        handed_over_by_student_id <> received_by_student_id
    )
);

-- Enforce LOST on the left and FOUND on the right of every candidate pair.
CREATE FUNCTION cp2_validate_match_report_types()
RETURNS TRIGGER AS $$
DECLARE
    actual_lost_type VARCHAR(5);
    actual_found_type VARCHAR(5);
BEGIN
    SELECT report_type INTO actual_lost_type
    FROM item_reports WHERE report_id = NEW.lost_report_id;
    SELECT report_type INTO actual_found_type
    FROM item_reports WHERE report_id = NEW.found_report_id;

    IF actual_lost_type IS DISTINCT FROM 'LOST'
       OR actual_found_type IS DISTINCT FROM 'FOUND' THEN
        RAISE EXCEPTION 'possible_matches requires a LOST report on the left and a FOUND report on the right';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER cp2_possible_match_types_trigger
BEFORE INSERT OR UPDATE OF lost_report_id, found_report_id ON possible_matches
FOR EACH ROW EXECUTE FUNCTION cp2_validate_match_report_types();

-- Do not change a report's LOST/FOUND role after it has been matched.
CREATE FUNCTION cp2_protect_matched_report_type()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.report_type <> OLD.report_type
       AND EXISTS (
           SELECT 1 FROM possible_matches
           WHERE lost_report_id = OLD.report_id OR found_report_id = OLD.report_id
       ) THEN
        RAISE EXCEPTION 'report_type cannot change while candidate matches exist';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER cp2_report_type_protection_trigger
BEFORE UPDATE OF report_type ON item_reports
FOR EACH ROW EXECUTE FUNCTION cp2_protect_matched_report_type();

-- A handover must have a verified APPROVED claim, never a pending candidate.
CREATE FUNCTION cp2_require_approved_claim()
RETURNS TRIGGER AS $$
DECLARE
    actual_status VARCHAR(10);
BEGIN
    SELECT verification_status INTO actual_status
    FROM ownership_claims WHERE claim_id = NEW.claim_id;
    IF actual_status IS DISTINCT FROM 'APPROVED' THEN
        RAISE EXCEPTION 'handover requires an APPROVED ownership claim';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER cp2_approved_handover_trigger
BEFORE INSERT OR UPDATE OF claim_id ON handovers
FOR EACH ROW EXECUTE FUNCTION cp2_require_approved_claim();

-- Once a handover exists, its claim must stay approved.
CREATE FUNCTION cp2_protect_handed_over_claim()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.verification_status <> 'APPROVED'
       AND EXISTS (SELECT 1 FROM handovers WHERE claim_id = OLD.claim_id) THEN
        RAISE EXCEPTION 'cannot revoke approval after a handover';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER cp2_claim_approval_protection_trigger
BEFORE UPDATE OF verification_status ON ownership_claims
FOR EACH ROW EXECUTE FUNCTION cp2_protect_handed_over_claim();

COMMIT;

